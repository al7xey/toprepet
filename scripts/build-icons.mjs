import { readFile, writeFile } from 'node:fs/promises';

// One monochrome source for navigation, controls and the article editor.
const sprite = await readFile(new URL('../src/new-design/ui/icons.svg', import.meta.url), 'utf8');
const aliases = {
  "arrow": "right",
  "left": "back",
  "cross": "x",
  "edit": "pen",
  "chat-bubble": "chat",
  "msg": "chat",
  "dot-check": "circle-check",
  "Bold": "bold",
  "Italic": "italic",
  "Strikethrough": "strikethrough",
  "Quote": "quote",
  "Table2": "table",
  "ImagePlus": "image-plus",
  "ListOrdered": "list-ordered",
  "Link2": "link",
  "List": "list",
  "Minus": "minus",
  "Trash2": "trash"
};
const symbols = [...sprite.matchAll(/<symbol id="ic-([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)];
if (symbols.length !== 69) throw new Error('Expected the complete minimal icon set');
const jsx = (body) => body
  .replaceAll('currentColor', 'var(--icon-ink,#202020)')
  .replace(/([a-z]+)-([a-z]+)=/g, (_, a, b) => a + b[0].toUpperCase() + b.slice(1) + '=');
const output = `// Generated by node scripts/build-icons.mjs from ui/icons.svg.
import type { ReactNode } from 'react';

export const iconArtwork: Record<string, ReactNode> = {
${symbols.map(([, name, body]) => `  '${name}': <>${jsx(body)}</>,`).join('\n')}
};

export const iconAliases: Record<string, string> = ${JSON.stringify(aliases, null, 2)};
`;
await writeFile(new URL('../src/new-design/ui/icon-artwork.tsx', import.meta.url), output);
console.log(`Generated ${symbols.length} icons and ${Object.keys(aliases).length} aliases`);
