import { readFile, writeFile } from 'node:fs/promises';

// The approved vector artwork stays editable alongside its review sheet.
const source = new URL('../design/icon-proposal-cartoon/', import.meta.url);
const sprite = await readFile(new URL('sprite.svg', source), 'utf8');
const aliases = JSON.parse(await readFile(new URL('aliases.json', source), 'utf8'));
const symbols = [...sprite.matchAll(/<symbol id="ic-([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)];
if (symbols.length !== 77) throw new Error('Expected the complete approved icon set');
const jsx = (body) => body
  .replaceAll('currentColor', 'var(--icon-ink,#202020)')
  .replace(/([a-z]+)-([a-z]+)=/g, (_, a, b) => a + b[0].toUpperCase() + b.slice(1) + '=');
const output = `// Generated by node scripts/build-icons.mjs from the approved SVG drawings.
import type { ReactNode } from 'react';

export const iconArtwork: Record<string, ReactNode> = {
${symbols.map(([, name, body]) => `  '${name}': <>${jsx(body)}</>,`).join('\n')}
};

export const iconAliases: Record<string, string> = ${JSON.stringify(aliases, null, 2)};
`;
await writeFile(new URL('../src/new-design/ui/icon-artwork.tsx', import.meta.url), output);
console.log(`Generated ${symbols.length} icons and ${Object.keys(aliases).length} aliases`);
